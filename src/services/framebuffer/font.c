static unsigned char glyph_index(unsigned char character)
{
    if (character >= '0' && character <= '9') {
        return (unsigned char)(4u + character - '0');
    }
    if (character >= 'A' && character <= 'Z') {
        return (unsigned char)(14u + character - 'A');
    }
    if (character >= 'a' && character <= 'z') {
        return (unsigned char)(14u + character - 'a');
    }
    if (character == '-') {
        return 1;
    }
    if (character == '+') {
        return 2;
    }
    if (character == '/') {
        return 3;
    }
    if (character == '.') {
        return 40;
    }
    if (character == ':') {
        return 41;
    }
    if (character == '(') {
        return 42;
    }
    if (character == ')') {
        return 43;
    }
    if (character == '[') {
        return 44;
    }
    if (character == ']') {
        return 45;
    }
    if (character == '>') {
        return 46;
    }
    if (character == '_') {
        return 47;
    }
    if (character == '~') {
        return 48;
    }
    if (character == '=') {
        return 49;
    }
    return 0;
}

unsigned char udeks_font_row(unsigned char character, unsigned char row)
{
    if (row >= UDEKS_FONT_HEIGHT) {
        return 0;
    }
    return (unsigned char)(glyphs[glyph_index(character)][row] << 3);
}

const unsigned char *udeks_font_glyph(unsigned char character)
{
    return glyphs[glyph_index(character)];
}
